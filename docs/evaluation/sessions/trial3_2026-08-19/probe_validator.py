"""Trial #3-A：validator 长上下文误拦复现分析。

E-03 现象：Trial #2-B 跨天场景「你还记得我是谁吗？」被 validator 拦截回退兜底。
本脚本系统化探测 validator 规则，找长上下文下可能的误判形态。
"""
import sys
sys.path.insert(0, r"C:\Users\11985\.qclaw\workspace\rezero_twin")

from shared.validators import ResponseValidator

v = ResponseValidator()

cases = [
    ("蕾姆正常含我(应拦? 第三人称约束)", '【蕾姆】: "我还记得您，客人大人。"'),
    ("蕾姆含我-否定式", '【蕾姆】: "我不会阻拦您。"'),
    ("蕾姆含我-疑问", '【蕾姆】: "我该怎么做才好？"'),
    ("拉姆含我(应放行)", '【拉姆】: "我可不会轻易相信。"'),
    ("拉姆含我-连续", '【拉姆】: "哼，我可没忘。姐姐我可记着呢。"'),
    ("蕾姆多段+拉姆(正常形态)", '【蕾姆】: "客人大人……"\n【蕾姆】: "蕾姆记得的，您说过您叫小东。"\n【拉姆】: "哼，我可没忘。"'),
    ("长回复+大量台词", '【蕾姆】: "蕾姆记得，那天您说自己是小东。"\n【拉姆】: "姐姐我也记得。"\n【蕾姆】: "蕾姆还泡了茶给您。"\n【拉姆】: "哼，还算有心。"'),
    ("OOC-用户词", '【蕾姆】: "用户您说笑了。"'),
    ("数值暴露", '【蕾姆】: "蕾姆的好感是 85/100。"'),
    ("缺少标签", '蕾姆记得您叫小东。'),
]

for name, t in cases:
    r = v.validate(t)
    print(f"{name:28} -> ok={r.ok} reason={r.reason}")
